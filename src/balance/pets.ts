/**
 * 小东西（纯数据）
 *
 * 狗、鸡、乡亲。它们**不是第四个村民**：「上场只有 3 人」是硬约束，
 * 保的是「看戏要认得出脸」（docs/01 §2）。狗不是人，所以它可以出现在场上，
 * 但必须一眼看出它不是村民 —— 画得小一号、不占队列格、不能装改装件。
 *
 * 核心设计：**小东西的强弱由主人决定，不由它自己决定。**
 *
 * 攻击和血量都按比例继承主人，出生位置就是主人站的那一格。所以
 * 「栓给谁」是一个真决策：
 *
 * - 栓给老烟枪（atk 210 / hp 680，站后排）：狗很猛但脆，还得跑一段才接敌
 * - 栓给铁柱（atk 62 / hp 1700，站队首）：狗不猛但耐揍，一出生就顶上去挡刀
 *
 * 做成固定数值就又变回了「装谁都一样」，直接撞反目标第一条。
 * 所以这里**没有 atk 那一栏** —— 攻击只能从主人身上来，差异要拉到最大。
 *
 * 反过来，**血量刻意写死在这儿，不跟主人走。**这一条试错了两轮：
 *
 * 1. 纯继承：老烟枪只有 680 血，狗跟着只剩一百来点，放出去就没了；
 *    铁柱 1700 血的狗却能一直挡刀。血量差（2.5 倍）压过攻击差，
 *    「栓给耐揍的」成了唯一答案。
 * 2. 保底加继承：差异还在往反方向抹 —— 栓给铁柱的狗攻击只有三分之一，
 *    却因为血厚、挡刀挡得久，把「装错人」的亏补了回来。2000 局回归里
 *    smart 与 random 的差值反而从 4.00 掉到 3.93。
 *
 * 血量一视同仁之后，「栓给谁」的差异才干净地落在攻击继承和学来的那一手上。
 */

export interface PetProto {
  id: string;
  /** 一眼知道是什么。别用奇幻词 */
  name: string;
  /** 血量。一视同仁，不看主人是谁 —— 理由见开头 */
  hp: number;
  /** 往前冲的速度（格／秒）。和外星人共用一套坐标，只是方向相反 */
  speed: number;
  attackIntervalMs: number;
  /** 能打几格。1 即贴脸 */
  range: number;
}

// 速度这一栏是**平衡旋钮，不是风味**。
//
// 小东西从主人脚下出生，所以栓给后排就得先跑一段。第一版狗只有 0.95，
// 那 4 秒空跑让「出生位置」的价值彻底压过了「继承攻击」：模拟里把狗栓给
// 攻击最高的老烟枪，反而比随手栓给队首更差（中位 10 波掉到 8）。
// 那样「栓给谁」就只有一个答案，这一件也就白做了。
// 狗跑得比人快本来也符合直觉，就用速度把位置的代价压回来。
export const PET_PROTOS: readonly PetProto[] = [
  // 狗最快，放出去就往前冲，所以它总是第一个接敌的
  { id: 'dog', name: '狗', hp: 205, speed: 1.55, attackIntervalMs: 800, range: 1 },
  // 鸡几乎不输出，慢慢挪到前面替人吃几下，价值全在挡刀，所以它不需要快也不需要肉
  { id: 'chicken', name: '鸡', hp: 135, speed: 0.5, attackIntervalMs: 1500, range: 1 },
  // 乡亲是来帮着打的，比村民利索一点
  { id: 'militia', name: '乡亲', hp: 245, speed: 0.8, attackIntervalMs: 1100, range: 1 },
];

export const PET_BY_ID: Readonly<Record<string, PetProto>> = Object.fromEntries(
  PET_PROTOS.map((p) => [p.id, p]),
);

export function getPetProto(id: string): PetProto {
  const p = PET_BY_ID[id];
  if (!p) throw new Error(`未知的小东西: ${id}`);
  return p;
}

/**
 * 全队同屏上限。
 *
 * 这个数守的是「看得清」，不是平衡。3 个村民 + 至多这么多小东西 + 涌进来的
 * 外星人，就是画面里同时能分辨的极限；再多就回到了当初 6 人上场时
 * 「满屏小人、看不清敌人」的老问题上。
 *
 * 每件改装件自己还有 maxAlive，那管的是单件强度；这一条是画面的硬闸。
 */
export const PET_CAP = 4;

/**
 * 小东西往前最多冲到哪。
 *
 * 这个数**必须待在村民的火力覆盖区里**。狗比外星人快得多，不设闸的话
 * 它会一路冲到出怪口把敌人拦在那儿 —— 而村民最远也就够到 3 格
 * （老烟枪站后排：-2 加射程 5）。第一版给了 4.2，结果整队集体空转，
 * 狗不是在帮忙，是在挡自己人的火线。
 */
export const PET_MAX_DIST = 1.4;
